-- Rodar de novo apaga a tabela e recria com os mesmos 4 pedidos.
--
--   psql "$BANCO" -v ON_ERROR_STOP=1 -f loja.sql
--
-- As contas e os pedidos são do kit. Os e-mails usam o domínio example, que não entrega
-- mensagem para ninguém.

begin;

-- Três clientes de teste. No Supabase, auth.users é a tabela de contas do Supabase Auth.
insert into auth.users (id, email) values
  ('11111111-1111-1111-1111-111111111111', 'bia@cliente.example'),
  ('22222222-2222-2222-2222-222222222222', 'caio@cliente.example'),
  ('33333333-3333-3333-3333-333333333333', 'duda@cliente.example')
on conflict (id) do nothing;

drop table if exists public.pedidos cascade;

create table public.pedidos (
  id bigint generated by default as identity primary key,
  cliente_id uuid not null default auth.uid() references auth.users (id),
  produto text not null,
  quantidade int not null,
  total_centavos int not null,
  status text not null default 'aguardando pagamento',
  cidade text,
  observacao text
);

insert into public.pedidos (id, cliente_id, produto, quantidade, total_centavos, status, cidade) values
  (1, '11111111-1111-1111-1111-111111111111', 'Luminária de mesa Aurora', 1, 24990, 'pago', 'Campinas'),
  (2, '11111111-1111-1111-1111-111111111111', 'Vela aromática Alecrim', 2, 13980, 'aguardando pagamento', 'Campinas'),
  (3, '22222222-2222-2222-2222-222222222222', 'Luminária de piso Arco', 1, 58900, 'pago', 'Sorocaba'),
  (4, '33333333-3333-3333-3333-333333333333', 'Manta de algodão Serra', 1, 15990, 'aguardando pagamento', 'Jundiaí');

select setval(pg_get_serial_sequence('public.pedidos', 'id'), 4);

-- O que o agente fez quando o Diego pediu "liga o RLS na tabela de pedidos".
alter table public.pedidos enable row level security;

-- Em muitos projetos, toda tabela nova em public já nasce com estas permissões.
-- O kit dá as mesmas de propósito, para o teste sair igual em qualquer projeto.
grant select, insert, update, delete on table public.pedidos to anon, authenticated;

create policy "Permitir tudo" on public.pedidos
  for all
  using (true);

commit;
